import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Script} from 'node:vm';
import ts from 'typescript';

// Keep the same classic-script entry point for file:// pages, Node and Workers.
const root = fileURLToPath(new URL('../', import.meta.url));
const print = diagnostics => ts.formatDiagnosticsWithColorAndContext(diagnostics, {
  getCurrentDirectory: () => root, getCanonicalFileName: name => name, getNewLine: () => '\n',
});
const config = ts.getParsedCommandLineOfConfigFile(path.join(root, 'tsconfig.json'), {
  noEmit: false, noEmitOnError: true, newLine: ts.NewLineKind.LineFeed,
  outDir: path.join(root, 'dist', 'formats-compiler'),
}, {...ts.sys, onUnRecoverableConfigFileDiagnostic: error => {throw new Error(print([error]));}});
const program = ts.createProgram(config.fileNames, config.options);
const diagnostics = [...config.errors, ...ts.getPreEmitDiagnostics(program)];
if (diagnostics.length) throw new Error(print(diagnostics));

function compile(relative) {
  const unit = program.getSourceFile(path.resolve(root, relative));
  if (!unit) throw new Error('Missing from tsconfig.json: '+relative);
  let compiled;
  const result = program.emit(unit, (name, text) => {if (name.endsWith('.js')) compiled = text;});
  if (result.emitSkipped || !compiled) throw new Error(print(result.diagnostics) || 'TypeScript emitted no JavaScript for '+relative);
  return compiled.trimEnd();
}

async function publish(relative, lines) {
  const destination = path.join(root, relative);
  const output = [...lines,''].join('\n').replace(/\r\n/g,'\n');
  new Script(output,{filename:relative});
  const previous = await readFile(destination,'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error;
    return '';
  });
  if (previous.replace(/\r\n/g,'\n') === output) return;
  if (process.argv.includes('--check')) throw new Error(relative+' is stale. Run npm run build:formats.');
  await writeFile(destination,output);
}

const adapter = await readFile(path.join(root, 'src/formats/workshop.js'), 'utf8');
await publish('js/formats.js', [
  '/* Generated by npm run build:formats from src/formats/. */',
  '(function () {', compile('src/formats/card-world.ts'), adapter.trimEnd(), '})();',
]);
for (const [source, destination] of [
  ['src/restore/work-restore.ts','js/work-restore.js'],
  ['src/creation/work-outcomes.ts','js/work-outcomes.js'],
]) {
  await publish(destination, ['/* Generated by npm run build:formats from '+source+'. */', compile(source)]);
}
const syncParts = await Promise.all(['phrases','session','panel'].map(name =>
  readFile(path.join(root, 'src/sync/world-sync-'+name+'.js'), 'utf8')));
await publish('js/world-sync.js', [
  '/* Generated by npm run build:formats from src/sync/. */',
  compile('src/sync/world-sync.ts'), ...syncParts.map(text => text.trimEnd()),
]);
console.log('Verified typed formats, selective backup restore, AI work outcomes, and world-book sync.');
